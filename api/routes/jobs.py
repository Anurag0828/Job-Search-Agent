# ============================================================
# API Routes: Jobs & Pipeline Management
# ============================================================
# PURPOSE:
#   Provides endpoints for viewing collected job postings,
#   viewing recommendations, recording user actions (applied, saved),
#   and manually triggering a job search pipeline run.
#
# ENDPOINTS:
#   GET  /api/jobs                 — List collected jobs (with filtering)
#   GET  /api/jobs/recommendations — Get latest recommended jobs
#   POST /api/jobs/run             — Trigger the Supervisor pipeline manually
#   POST /api/jobs/{id}/action     — Record user action (applied, saved, etc.)
#
# ============================================================

from typing import Optional, List
from fastapi import APIRouter, HTTPException, BackgroundTasks, Query
from pydantic import BaseModel
from database.connection import get_db
from database.models import JobPostingModel, RecommendationModel, RunLogModel
from agents.memory_agent import MemoryAgent
from agents.supervisor import SupervisorAgent


router = APIRouter()


class ActionRequest(BaseModel):
    """Payload for recording user action on a job."""
    action: str  # "applied", "not_interested", "saved", "none"


@router.get("", response_model=dict)
async def list_jobs(
    platform: Optional[str] = None,
    min_score: Optional[float] = None,
    recommended_only: bool = False,
    limit: int = Query(50, le=200),
    offset: int = 0,
):
    """
    List collected job postings from the database with filtering.
    
    Query Parameters:
        platform: Filter by source platform (e.g., "linkedin_jobs", "naukri")
        min_score: Filter by minimum AI match score (0-100)
        recommended_only: If true, only return jobs that were sent in recommendations
        limit: Max number of results to return (default 50, max 200)
        offset: Pagination offset
    """
    db = get_db()
    try:
        query = db.query(JobPostingModel).filter(JobPostingModel.is_duplicate == False)

        if platform:
            query = query.filter(JobPostingModel.platform == platform)
        if min_score is not None:
            query = query.filter(JobPostingModel.match_score >= min_score)
        if recommended_only:
            query = query.filter(JobPostingModel.is_recommended == True)

        total_count = query.count()
        jobs = query.order_by(JobPostingModel.match_score.desc().nullslast(), JobPostingModel.collected_at.desc()).offset(offset).limit(limit).all()

        results = []
        for j in jobs:
            results.append({
                "id": j.id,
                "title": j.title,
                "company": j.company,
                "location": j.location,
                "url": j.url,
                "platform": j.platform,
                "posted_date": j.posted_date,
                "salary": j.salary,
                "match_score": j.match_score,
                "match_rationale": j.match_rationale,
                "missing_skills": j.missing_skills or [],
                "is_recommended": j.is_recommended,
                "user_action": j.user_action,
                "collected_at": j.collected_at.isoformat() if j.collected_at else None,
            })

        return {
            "status": "success",
            "total": total_count,
            "limit": limit,
            "offset": offset,
            "jobs": results,
        }
    finally:
        db.close()


@router.get("/recommendations", response_model=dict)
async def get_recommendations(limit: int = 20):
    """
    Get the latest job recommendations generated by the system.
    """
    db = get_db()
    try:
        recs = db.query(RecommendationModel).order_by(RecommendationModel.recommended_at.desc()).limit(limit).all()
        
        results = []
        for r in recs:
            # Fetch corresponding job details
            job = db.query(JobPostingModel).filter(JobPostingModel.id == r.job_posting_id).first()
            results.append({
                "id": r.id,
                "job_posting_id": r.job_posting_id,
                "title": job.title if job else "Unknown Title",
                "company": job.company if job else "Unknown Company",
                "location": job.location if job else None,
                "url": job.url if job else "#",
                "platform": job.platform if job else "unknown",
                "match_score": r.match_score,
                "rationale": r.rationale,
                "missing_skills": r.missing_skills or [],
                "rank_position": r.rank_position,
                "user_action": r.user_action,
                "recommended_at": r.recommended_at.isoformat() if r.recommended_at else None,
            })

        return {
            "status": "success",
            "count": len(results),
            "recommendations": results,
        }
    finally:
        db.close()


@router.post("/{job_id}/action", response_model=dict)
async def record_action(job_id: int, payload: ActionRequest):
    """
    Record a user action on a job posting (e.g., "applied", "not_interested", "saved").
    
    This feedback is used by the Memory Agent to improve future recommendations.
    """
    valid_actions = ["applied", "not_interested", "saved", "none"]
    if payload.action not in valid_actions:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid action. Must be one of: {valid_actions}"
        )

    memory_agent = MemoryAgent()
    action_val = None if payload.action == "none" else payload.action
    memory_agent.record_user_action(job_id, action_val or "")

    return {
        "status": "success",
        "message": f"Action '{payload.action}' recorded for job {job_id}",
    }


def _run_pipeline_background():
    """Background task function to execute the supervisor pipeline."""
    print("[API] Background pipeline run started...")
    supervisor = SupervisorAgent()
    supervisor.run_pipeline()
    print("[API] Background pipeline run finished.")


@router.post("/run", response_model=dict)
async def trigger_pipeline_run(background_tasks: BackgroundTasks):
    """
    Manually trigger a full job search pipeline run in the background.
    
    The pipeline will collect jobs from LinkedIn & Naukri, match and score them
    against your resume, filter duplicates, and send the email digest.
    """
    background_tasks.add_task(_run_pipeline_background)
    return {
        "status": "started",
        "message": "Job search pipeline started in the background. Check logs or /api/jobs for updates.",
    }


@router.get("/logs", response_model=dict)
async def get_run_logs(limit: int = 10):
    """
    Get execution logs of past daily pipeline runs.
    """
    db = get_db()
    try:
        logs = db.query(RunLogModel).order_by(RunLogModel.started_at.desc()).limit(limit).all()
        results = []
        for l in logs:
            results.append({
                "id": l.id,
                "status": l.status,
                "started_at": l.started_at.isoformat() if l.started_at else None,
                "completed_at": l.completed_at.isoformat() if l.completed_at else None,
                "jobs_collected": l.jobs_collected,
                "jobs_new": l.jobs_new,
                "jobs_matched": l.jobs_matched,
                "recommendations_sent": l.recommendations_sent,
                "collector_errors": l.collector_errors,
                "error_message": l.error_message,
            })
        return {
            "status": "success",
            "logs": results,
        }
    finally:
        db.close()
